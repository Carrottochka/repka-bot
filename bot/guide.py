def section_by_id(section_id: str) -> Section | None:
    for section in SECTIONS:
        if section.id == section_id:
            return section
    return None


def lesson_by_id(lesson_id: str) -> tuple[Section, Lesson] | None:
    for section in SECTIONS:
        for lesson in section.lessons:
            if lesson.id == lesson_id:
                return section, lesson
    return None


def all_lessons() -> list[Lesson]:
    return [lesson for section in SECTIONS for lesson in section.lessons]
