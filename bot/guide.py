from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Lesson:
    id: str
    button: str
    title: str
    body: str


@dataclass(frozen=True)
class Section:
    id: str
    button: str
    intro: str
    lessons: tuple[Lesson, ...]


def _lesson(lesson_id: str, button: str, title: str, body: str) -> Lesson:
    return Lesson(id=lesson_id, button=button, title=title, body=body.strip())


